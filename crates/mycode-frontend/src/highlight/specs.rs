//! The lexical shape of every colored language family: keywords, types,
//! literals, comment markers, quote rules, and the flags the lexer reads.
/// The lexical shape of one language family.
pub(super) struct Spec {
    pub(super) keywords: &'static [&'static str],
    pub(super) types: &'static [&'static str],
    pub(super) literals: &'static [&'static str],
    pub(super) line_comments: &'static [&'static str],
    pub(super) block_comment: Option<(&'static str, &'static str)>,
    pub(super) quotes: &'static [u8],
    /// Quotes whose strings may run past a newline.
    pub(super) multiline_quotes: &'static [u8],
    pub(super) escape: Option<u8>,
    /// `"""` and `'''` strings.
    pub(super) triple_quotes: bool,
    /// Words that prefix a string literal (`f"…"`, `b"…"`), lowercase.
    pub(super) string_prefixes: &'static [&'static str],
    /// `'` is a char literal or a lifetime, `r#"…"#` raw strings, `name!`
    /// macros, and `#[…]` attributes.
    pub(super) rust: bool,
    /// `#include`-style directives at the start of a line.
    pub(super) preprocessor: bool,
    /// `@name` decorators and annotations.
    pub(super) decorators: bool,
    /// `$name` variables.
    pub(super) sigils: bool,
    /// `-flag` and `--flag` after whitespace.
    pub(super) flags: bool,
    /// Identifiers may contain `-` (`Get-ChildItem`, `apt-get`).
    pub(super) dash_idents: bool,
    /// Capitalized words are types; `ALL_CAPS` words are constants.
    pub(super) capital_types: bool,
    pub(super) ignore_case: bool,
    /// A string followed by `:` is an object key.
    pub(super) json_keys: bool,
    /// `key:` (YAML) or `key =` (TOML, INI) at the start of a line.
    pub(super) line_key: Option<u8>,
}

